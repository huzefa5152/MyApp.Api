import assert from 'node:assert/strict';
import { createInFlightRead } from '../src/utils/inFlightRead.js';
let scope='user-a', calls=0;
const tasks=[];
const deferred=()=>{let resolve,reject;const promise=new Promise((a,b)=>{resolve=a;reject=b;});return {promise,resolve,reject};};
const read=createInFlightRead((id)=>{calls++;const task=deferred();tasks.push({id,...task});return task.promise;},()=>scope);
const first=read(1),second=read(1),third=read(1);
assert.equal(first,second);assert.equal(second,third);assert.equal(calls,1);
tasks[0].resolve({data:['sample']});assert.deepEqual(await first,{data:['sample']});
const fresh=read(1);assert.equal(calls,2);
scope='user-b';const anotherUser=read(1);assert.equal(calls,3);assert.notEqual(fresh,anotherUser);
const anotherCompany=read(2);assert.equal(calls,4);
read.clear();const afterWrite=read(1);assert.equal(calls,5);
tasks[2].resolve('old');await anotherUser;
assert.equal(read(1),afterWrite);
for(const n of [1,3,4])tasks[n].resolve(n);
await Promise.all([fresh,anotherCompany,afterWrite]);
const failed=read(1);const error=new Error('temporary');tasks[5].reject(error);await assert.rejects(failed,e=>e===error);
const retry=read(1);assert.equal(calls,7);tasks[6].resolve('recovered');assert.equal(await retry,'recovered');
console.log('PASS: 3 simultaneous reads -> 1 request; settled freshness, user/company scope, invalidation, old completion and error recovery.');
